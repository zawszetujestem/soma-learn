it('breadcrumb pokazuje pełną ścieżkę i nawigacja rodzic/dziecko/rodzeństwo zachowuje modal oraz szkice',async()=>{
 const sibling={...lesson,id:14,title:'Lekcja druga'}
 const item={id:50,format:'text',text:'Zadanie',answer_mode:'open'}
 const topic={...version.nodes[0].children[0],children:[{...lesson,practice:[item]},sibling]}
 const {calls}=mockApi(editorApi({},MENTOR,{...version,nodes:[{...version.nodes[0],children:[topic]}]}))
 renderApp(editorPath);const u=userEvent.setup()
 await u.click(await screen.findByRole('button',{name:'Zadanie 1: Lekcja pierwsza'}))
 const dialog=screen.getByRole('dialog',{name:'Szczegóły — Zadanie 1: Lekcja pierwsza'})
 const path=within(dialog).getByRole('navigation',{name:'Ścieżka elementu'})
 expect(within(path).getAllByRole('listitem').map(e=>e.textContent)).toEqual(['Dział pierwszy','Temat pierwszy','Lekcja pierwsza','Zadanie 1: Lekcja pierwsza'])
 expect(within(path).getByText('Zadanie 1: Lekcja pierwsza')).toHaveAttribute('aria-current','page')
 await u.type(screen.getByLabelText('Treść materiału 50'),' szkic materiału')
 await u.click(within(path).getByRole('button',{name:'Lekcja pierwsza'}))
 expect(screen.getByRole('dialog')).toBe(dialog)
 expect(dialog).toHaveAccessibleName('Szczegóły — Lekcja: Lekcja pierwsza')
 const draft=screen.getByLabelText('Nazwa Lekcja pierwsza')
 await u.type(draft,' szkic lekcji')
 await u.click(within(path).getByRole('button',{name:'Temat pierwszy'}))
 expect(screen.getByRole('dialog')).toBe(dialog)
 await u.click(within(dialog).getByRole('button',{name:'Lekcja: Lekcja druga'}))
 expect(screen.getByLabelText('Nazwa Lekcja druga')).toHaveValue('Lekcja druga')
 await u.type(screen.getByLabelText('Nazwa Lekcja druga'),' drugi szkic')
 await u.click(within(path).getByRole('button',{name:'Temat pierwszy'}))
 await u.click(within(dialog).getByRole('button',{name:'Lekcja: Lekcja pierwsza'}))
 expect(screen.getByLabelText('Nazwa Lekcja pierwsza')).toBe(draft)
 expect(draft).toHaveValue('Lekcja pierwsza szkic lekcji')
 expect(screen.getByLabelText('Treść materiału 50')).toHaveValue('Zadanie szkic materiału')
 await u.click(within(path).getByRole('button',{name:'Temat pierwszy'}))
 await u.click(within(dialog).getByRole('button',{name:'Lekcja: Lekcja druga'}))
 expect(screen.getByLabelText('Nazwa Lekcja druga')).toHaveValue('Lekcja druga drugi szkic')
 await u.click(within(path).getByRole('button',{name:'Dział pierwszy'}))
 expect(within(path).queryByRole('button')).not.toBeInTheDocument()
 expect(within(path).getByText('Dział pierwszy')).toHaveAttribute('aria-current','page')
 expect(screen.getByRole('dialog')).toBe(dialog)
 expect(document.querySelector('main')).toHaveAttribute('inert')
 expect(document.body.style.overflow).toBe('hidden')
 expect(screen.queryByRole('alert')).not.toBeInTheDocument()
 await u.click(within(dialog).getByRole('button',{name:'Zamknij'}))
 expect(screen.getByRole('alert')).toHaveTextContent('Niezapisane zmiany pozostaną w szkicu.')
 expect(calls.every(c=>c.method==='GET')).toBe(true)
})

